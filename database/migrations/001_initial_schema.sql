-- Cleidson Diesel - initial PostgreSQL schema
-- This migration only defines the database structure. It does not contain customer data.
-- Apply only to a newly provisioned PostgreSQL database after reviewing the deployment plan.

create extension if not exists pgcrypto;

create table if not exists customers (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  document_number text,
  phone text,
  email text,
  address text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists vehicles (
  id uuid primary key default gen_random_uuid(),
  customer_id uuid not null references customers(id) on delete restrict,
  plate text,
  make text,
  model text,
  model_year integer,
  engine_description text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint vehicles_model_year_valid check (model_year is null or model_year between 1900 and 2200)
);

create unique index if not exists vehicles_plate_unique
  on vehicles (upper(regexp_replace(plate, '[^A-Za-z0-9]', '', 'g')))
  where plate is not null and btrim(plate) <> '';

create table if not exists work_orders (
  id uuid primary key default gen_random_uuid(),
  order_number bigint generated by default as identity unique,
  customer_id uuid not null references customers(id) on delete restrict,
  vehicle_id uuid references vehicles(id) on delete restrict,
  status text not null default 'open'
    check (status in ('open', 'in_progress', 'awaiting_approval', 'approved', 'completed', 'cancelled')),
  complaint text,
  diagnosis text,
  observations text,
  opened_at timestamptz not null default now(),
  completed_at timestamptz,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists work_order_items (
  id uuid primary key default gen_random_uuid(),
  work_order_id uuid not null references work_orders(id) on delete cascade,
  description text not null,
  quantity numeric(12,2) not null default 1 check (quantity > 0),
  unit_price numeric(12,2) not null default 0 check (unit_price >= 0),
  line_total numeric(12,2) not null default 0 check (line_total >= 0),
  created_at timestamptz not null default now()
);

create table if not exists payments (
  id uuid primary key default gen_random_uuid(),
  work_order_id uuid not null references work_orders(id) on delete restrict,
  amount numeric(12,2) not null check (amount > 0),
  payment_method text not null
    check (payment_method in ('cash', 'pix', 'debit_card', 'credit_card', 'transfer', 'other')),
  paid_at timestamptz not null default now(),
  reference text,
  notes text,
  created_at timestamptz not null default now()
);

create table if not exists warranties (
  id uuid primary key default gen_random_uuid(),
  work_order_id uuid not null unique references work_orders(id) on delete restrict,
  starts_on date not null,
  expires_on date not null,
  terms text,
  created_at timestamptz not null default now(),
  constraint warranty_dates_valid check (expires_on >= starts_on)
);

create index if not exists vehicles_customer_id_idx on vehicles(customer_id);
create index if not exists work_orders_customer_id_idx on work_orders(customer_id);
create index if not exists work_orders_vehicle_id_idx on work_orders(vehicle_id);
create index if not exists work_orders_status_idx on work_orders(status);
create index if not exists payments_work_order_id_idx on payments(work_order_id);
create index if not exists warranties_expires_on_idx on warranties(expires_on);

create or replace function set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists customers_set_updated_at on customers;
create trigger customers_set_updated_at before update on customers
for each row execute function set_updated_at();

drop trigger if exists vehicles_set_updated_at on vehicles;
create trigger vehicles_set_updated_at before update on vehicles
for each row execute function set_updated_at();

drop trigger if exists work_orders_set_updated_at on work_orders;
create trigger work_orders_set_updated_at before update on work_orders
for each row execute function set_updated_at();

