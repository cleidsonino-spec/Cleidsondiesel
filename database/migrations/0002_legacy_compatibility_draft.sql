-- Objetivo: aproximar o schema simplificado já existente do modelo usado
-- pelo aplicativo legado, sem apagar ou renomear as cinco tabelas atuais.
-- A aplicação ainda depende do Supabase; esta migration não integra o app.

BEGIN;

-- Complementa service_orders sem remover os campos já existentes.
ALTER TABLE public.service_orders
  ADD COLUMN IF NOT EXISTS number bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS plate text,
  ADD COLUMN IF NOT EXISTS customer_name text,
  ADD COLUMN IF NOT EXISTS phone text,
  ADD COLUMN IF NOT EXISTS vehicle text,
  ADD COLUMN IF NOT EXISTS vehicle_year text,
  ADD COLUMN IF NOT EXISTS mileage text,
  ADD COLUMN IF NOT EXISTS complaint text,
  ADD COLUMN IF NOT EXISTS diagnosis text,
  ADD COLUMN IF NOT EXISTS parts text,
  ADD COLUMN IF NOT EXISTS part_items jsonb,
  ADD COLUMN IF NOT EXISTS parts_value numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS labor_value numeric(12,2) NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS entry_date date NOT NULL DEFAULT current_date,
  ADD COLUMN IF NOT EXISTS due_date date,
  ADD COLUMN IF NOT EXISTS notes text,
  ADD COLUMN IF NOT EXISTS appointment_id uuid,
  ADD COLUMN IF NOT EXISTS created_by uuid,
  ADD COLUMN IF NOT EXISTS inspection_checklist jsonb NOT NULL DEFAULT '[]'::jsonb,
  ADD COLUMN IF NOT EXISTS updated_at timestamptz NOT NULL DEFAULT now();

CREATE UNIQUE INDEX IF NOT EXISTS service_orders_number_unique
  ON public.service_orders(number);
CREATE INDEX IF NOT EXISTS service_orders_plate_idx
  ON public.service_orders(plate);
CREATE INDEX IF NOT EXISTS service_orders_entry_date_idx
  ON public.service_orders(entry_date);

-- Agendamentos: tabela nova, sem conflito com as cinco tabelas existentes.
CREATE TABLE IF NOT EXISTS public.appointments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  customer_name text NOT NULL,
  phone text NOT NULL,
  plate text NOT NULL,
  vehicle text NOT NULL,
  service_type text NOT NULL,
  scheduled_date date NOT NULL,
  scheduled_time time NOT NULL,
  notes text,
  status varchar(30) NOT NULL DEFAULT 'pendente',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS appointments_slot_unique
  ON public.appointments(scheduled_date, scheduled_time)
  WHERE status <> 'cancelado';
CREATE INDEX IF NOT EXISTS appointments_plate_idx
  ON public.appointments(plate);

-- Relaciona opcionalmente uma ordem a um agendamento.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'service_orders_appointment_id_fkey'
      AND conrelid = 'public.service_orders'::regclass
  ) THEN
    ALTER TABLE public.service_orders
      ADD CONSTRAINT service_orders_appointment_id_fkey
      FOREIGN KEY (appointment_id) REFERENCES public.appointments(id)
      ON DELETE SET NULL;
  END IF;
END $$;

-- Aprovação de orçamento por token. Regras e endpoints serão implementados
-- no servidor depois da definição da autenticação independente.
CREATE TABLE IF NOT EXISTS public.quote_approvals (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.service_orders(id) ON DELETE CASCADE,
  token text NOT NULL UNIQUE,
  snapshot jsonb NOT NULL,
  state varchar(20) NOT NULL DEFAULT 'pending'
    CHECK (state IN ('pending', 'approved', 'revoked')),
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL DEFAULT now() + interval '7 days',
  approved_at timestamptz,
  approved_by text,
  approved_cpf text
);

CREATE INDEX IF NOT EXISTS quote_approvals_order_idx
  ON public.quote_approvals(order_id, created_at DESC);

COMMIT;

